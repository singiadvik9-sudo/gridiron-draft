// how good this defensive call is against this offensive play (positive: good for the defense)
function matchup(defPick, offPick) {
  const dc = DEF_CALLS[defPick] || DEF_CALLS.ZONE, oc = OFF[offPick];
  if (!oc || !MATCH[dc.cat][oc.cat]) return 0;
  const a = dc.adj || {}, v = oc.vs || {};
  return clamp(MATCH[dc.cat][oc.cat] + (a[oc.cat] || 0) + (a[offPick] || 0) + (v[dc.cat] || 0) + (v[defPick] || 0), -1.4, 1.6);
}

function fgDist(st) { return 100 - st.ballOn + 17; }
// plays where the defense does not need to call anything
const noDef = pick => { const p = OFF[pick] || KICKS[pick]; return !p || (p.kind !== 'run' && p.kind !== 'pass'); };
function legalOff(st, pick) {
  if (st.kick) return KICKS[pick] ? pick : 'KO';
  if (!OFF[pick]) return 'RUN_IN';
  if ((pick === 'SPIKE' || pick === 'KNEEL') && st.down === 4) return 'RUN_IN';
  if ((pick === 'PUNT' || pick === 'FG') && st.down < 4) return 'RUN_IN';
  if (pick === 'FG' && fgDist(st) > 62) return 'PUNT';
  return pick;
}
function offOptions(st) {
  if (st.kick) return Object.keys(KICKS).map(id => ({ id, cat: 'KICKOFF', label: KICKS[id].label, desc: KICKS[id].desc, disabled: false, note: '' }));
  return Object.keys(OFF).map(id => {
    let disabled = false, note = '';
    if ((id === 'PUNT' || id === 'FG') && st.down < 4) { disabled = true; note = '4th down'; }
    if (id === 'FG' && fgDist(st) > 62) { disabled = true; note = 'Out of range'; }
    if ((id === 'SPIKE' || id === 'KNEEL') && st.down === 4) { disabled = true; note = '1st-3rd down'; }
    if (id === 'SPIKE' && !disabled && !(st.ro > 0)) { disabled = true; note = 'Clock is stopped'; }
    if (id === 'FG' && !disabled) note = fgDist(st) + ' yds';
    return { id, cat: OFF[id].cat, label: OFF[id].label, desc: OFF[id].desc, disabled, note };
  });
}
function defOptions() { return Object.keys(DEF_CALLS).map(id => ({ id, cat: DEF_CALLS[id].cat, label: DEF_CALLS[id].label, desc: DEF_CALLS[id].desc, disabled: false, note: '' })); }

/* ================= game state ================= */
function initState(seed) {
  const firstRecv = (seed % 2 === 0) ? 'a' : 'b';
  return { poss: firstRecv, firstRecv, ballOn: 25, down: 1, toGo: 10, score: { a: 0, b: 0 },
           playNo: 0, over: false, winner: null, ot: false, q: 1, clock: QLEN, ro: 0, to: { a: TO_HALF, b: TO_HALF }, kick: null, fat: {} };
}
// ro: seconds that ran off after the last snap while the clock was still going (a timeout before the next snap takes them back)
function clockInfo(st) {
  const c = Math.max(0, st.clock), t = Math.floor(c / 60) + ':' + ('0' + (c % 60)).slice(-2);
  return { q: st.ot ? 'OT' : 'Q' + st.q, clock: c, text: t, running: st.ro > 0 };
}

function stepGame(st, teams, U, seed, offPickRaw, defPickRaw, live, flags, rv) {
  const R = mulberry32(hashStr(seed + ':' + st.playNo));
  const gauss = () => (R() + R() + R() + R() - 2) * 1.7320508;
  const o = st.poss, d = o === 'a' ? 'b' : 'a';
  const OU = U[o], DU = U[d];
  const offPick = legalOff(st, offPickRaw);
  const isKick = noDef(offPick);
  const defPick = DEF_CALLS[defPickRaw] ? defPickRaw : 'ZONE';
  const OC = OFF[offPick] || KICKS[offPick], DC = DEF_CALLS[defPick], ocat = OC.cat;
  const s = Object.assign({}, st, { score: { a: st.score.a, b: st.score.b }, to: { a: st.to.a, b: st.to.b } });
  const nm = (t, id) => nameOf(teams[t], id);
  const entry = {
    n: st.playNo, off: o, offPick, defPick: isKick ? null : defPick, ev: 'play', text: '',
    yards: 0, travel: 0, anim: 'run', pts: 0, ptsTeam: null,
    before: { poss: o, ballOn: st.ballOn, down: st.down, toGo: st.toGo }, q: st.ot ? 'OT' : 'Q' + st.q, clk: st.clock
  };
  // timeouts called before the snap stop the clock: whatever ran off since the last play is given back
  const tos = [];
  if (flags) [['o', o], ['d', d]].forEach(([k, t]) => { if (flags[k] && st.ro > 0 && s.to[t] > 0) { s.to[t]--; tos.push(t); } });
  if (tos.length) { s.clock = st.clock + st.ro; s.ro = 0; entry.timeouts = tos; }
  let pt = 4, stopFlag = false;   // seconds the play itself took; does the clock stop when it ends?
  const giveBall = (team, on) => {
    s.poss = team; s.ballOn = clamp(Math.round(on), 1, 99); s.down = 1; s.toGo = Math.min(10, 100 - s.ballOn);
  };
  const other = t => t === 'a' ? 'b' : 'a';
  // the first kick of a snap that somebody may run back by hand (a punt, a kickoff after a score): rv is how that return went on the field
  let retCount = 0;
  const retFrom = (kind, kicker, recv, at, rnd) => {
    // returns the played-out result for this kick (or null when it is left to the dice)
    if (retCount++) return null;
    entry.retOpp = { kind, kicker, recv, at };
    if (rv && rv.kind === kind) { entry.rvLive = true; return rv; }
    return null;
  };
  // kickoff: touchback or a return that depends on the kicker's leg, the returner and both special-teams units
  const kickoff = (kicker, recv) => {
    const KU = U[kicker], RU = U[recv], kk = nm(kicker, 'K'), rr = nm(recv, 'KR');
    if (R() < clamp(0.5 + (KU.k - 72) * 0.012, 0.2, 0.85)) { giveBall(recv, 30); entry.ko = 30; return kk + ' kicks it deep for a touchback.'; }
    const sk = (RU.krR - 78) / 14, cv = (KU.stc - 72) / 12, bl = (RU.stc - 72) / 12;
    let r = 23 + gauss() * 5 + sk * 5 - cv * 2.5 + bl * 1.5;
    if (R() < 0.03 + Math.max(0, sk) * 0.05) r += 18 + R() * 30;
    const at = 3 + Math.floor(R() * 5);
    const played = retFrom('ko', kicker, recv, at);
    const lead = kk + ' kicks off. ';
    if (played) {
      const sp = at + played.x;
      if (played.td || sp >= 100) { entry.rtd = recv; return lead + rr + ' takes it all the way back!' + scoreTD(recv, ''); }
      if (played.fumble) { const fs = clamp(Math.round(sp), 1, 99); giveBall(kicker, 100 - fs); entry.ko = fs; return lead + rr + ' fumbles the return and ' + teams[kicker].name + ' recovers.'; }
      if (played.tb || sp <= 0) { giveBall(recv, 25); entry.ko = 25; return lead + rr + ' is stopped in the end zone. Touchback.'; }
      const spot = clamp(Math.round(sp), 1, 99); giveBall(recv, spot); entry.ko = spot;
      return lead + rr + ' returns it to the ' + (spot > 50 ? 'opponent ' + (100 - spot) : 'own ' + spot) + '.';
    }
    const spot = clamp(Math.round(r), 12, 70); giveBall(recv, spot); entry.ko = spot;
    return lead + rr + ' returns it to the ' + (spot > 50 ? 'opponent ' + (100 - spot) : 'own ' + spot) + '.';
  };
  // after a score the scorer kicks off: a step of its own, where the kicking team chooses between a deep kick and an onside kick
  const setKick = (kicker, recv) => { s.kick = { k: kicker, r: recv }; s.poss = kicker; s.ballOn = 35; s.down = 1; s.toGo = 10; };
  const scoreTD = (team, desc) => {
    s.score[team] += 6; entry.pts = 6; entry.ptsTeam = team; entry.ev = 'td';
    if (!st.ot) {
      const good = R() < clamp(0.90 + (U[team].k - 60) * 0.002, 0.7, 0.995);
      if (good) { s.score[team] += 1; entry.pts = 7; desc += ' The extra point is good.'; }
      else desc += ' The extra point is missed.';
      setKick(team, other(team));
    } else giveBall(other(team), 25);
    return desc;
  };
  const safety = (desc) => {
    s.score[d] += 2; entry.pts = 2; entry.ptsTeam = d; entry.ev = 'safety';
    giveBall(d, 35);
    return desc + ' Safety, two points.';
  };
  // shared yardage application for completed runs / passes
  const advance = (y, desc) => {
    const nb = st.ballOn + y;
    entry.yards = y;
    if (nb >= 100) return scoreTD(o, desc + ' Touchdown!');
    if (nb <= 0) return safety(desc);
    if (y >= st.toGo) {
      s.ballOn = nb; s.down = 1; s.toGo = Math.min(10, 100 - nb); entry.firstDown = true;
      return desc + ' First down.';
    }
    s.ballOn = nb; s.toGo = st.toGo - y; s.down = st.down + 1;
    if (s.down > 4) { giveBall(d, 100 - nb); entry.ev = 'downs'; return desc + ' Turnover on downs.'; }
    return desc;
  };
  const yds = y => Math.abs(y) === 1 ? '1 yard' : Math.abs(y) + ' yards';

  if (st.kick) {
    // the kickoff after a score / at the half / starting overtime
    pt = 0; stopFlag = true; s.kick = null; entry.ev = 'kickoff'; entry.anim = 'punt';
    const KU = U[o], RU = U[d];
    if (offPick === 'ONSIDE') {
      entry.travel = 10;
      if (R() < clamp(0.12 + (KU.stc - RU.stc) * 0.0025, 0.05, 0.25)) { giveBall(o, 45); entry.onside = 'kept'; entry.text = nm(o, 'K') + ' squibs an onside kick and ' + teams[o].name + ' keep the ball!'; }
      else { giveBall(d, 55); entry.onside = 'lost'; entry.text = nm(o, 'K') + ' tries an onside kick, but ' + teams[d].name + ' fall on it at midfield.'; }
    } else { entry.travel = 60; entry.text = kickoff(o, d); }
  } else if (offPick === 'SPIKE') {
    s.down = st.down + 1; entry.anim = 'spike'; entry.ev = 'spike'; pt = 1; stopFlag = true;
    entry.text = nm(o, 'QB') + ' spikes the ball to stop the clock.';
    if (s.down > 4) { giveBall(d, 100 - st.ballOn); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
  } else if (offPick === 'KNEEL') {
    const nb = Math.max(1, st.ballOn - 1), lost = st.ballOn - nb;
    s.ballOn = nb; s.toGo = st.toGo + lost; s.down = st.down + 1; entry.anim = 'kneel'; entry.ev = 'kneel'; entry.travel = -lost; entry.yards = -lost; pt = 3;
    entry.text = nm(o, 'QB') + ' takes a knee.';
  } else if (offPick === 'PUNT') {
    pt = 5;
    const dist = Math.round(clamp(38 + (OU.pu - 55) * 0.22 + gauss() * 5, 22, 62));
    const land = st.ballOn + dist;
    entry.ev = 'punt'; entry.anim = 'punt'; entry.travel = dist;
    if (land >= 100) {
      giveBall(d, 20);
      entry.text = nm(o, 'P') + ' punts it into the end zone. Touchback.';
    } else {
      const rs = (DU.prR - 78) / 14, cv = (OU.stc - 72) / 12;
      let ret = Math.max(0, Math.round(R() * 8 * (0.75 + 0.6 * rs - 0.35 * cv)));
      if (R() < 0.02 + Math.max(0, rs) * 0.03) ret += 15 + Math.round(R() * 30);
      ret = Math.min(ret, 100 - (100 - land) - 1);
      const at = 100 - land, played = retFrom('pr', o, d, at);
      if (played) {
        const sp = at + played.x;
        entry.ret = { x: played.x };
        if (played.fc) { giveBall(d, at); entry.text = nm(o, 'P') + ' punts ' + dist + ' yards. Fair catch by ' + nm(d, 'PR') + '.'; }
        else if (played.td || sp >= 100) {
          entry.rtd = d;
          entry.text = nm(o, 'P') + ' punts ' + dist + ' yards and ' + nm(d, 'PR') + ' takes it back for a touchdown!' + scoreTD(d, '');
        }
        else if (played.fumble) { const fs = clamp(Math.round(sp), 1, 99); giveBall(o, 100 - fs); entry.text = nm(o, 'P') + ' punts ' + dist + ' yards. ' + nm(d, 'PR') + ' fumbles the return and ' + teams[o].name + ' recovers.'; }
        else if (played.tb || sp <= 0) { giveBall(d, 20); entry.text = nm(o, 'P') + ' punts ' + dist + ' yards. ' + nm(d, 'PR') + ' is stopped in the end zone. Touchback.'; }
        else {
          const rr = Math.round(played.x);
          giveBall(d, clamp(Math.round(sp), 1, 99));
          entry.text = nm(o, 'P') + ' punts ' + dist + ' yards' + (rr > 2 ? ', ' + nm(d, 'PR') + ' returns it ' + rr : '') + '.';
        }
      } else {
        giveBall(d, 100 - land + ret);
        entry.text = nm(o, 'P') + ' punts ' + dist + ' yards' + (ret > 2 ? ', ' + nm(d, 'PR') + ' returns it ' + ret : '') + '.';
      }
    }
  } else if (offPick === 'FG') {
    pt = 3;
    const dist = fgDist(st);
    const p = clamp(0.985 - Math.max(0, dist - 24) * 0.0175 + (OU.k - 60) * 0.004, 0.04, 0.99);
    entry.anim = 'fg'; entry.travel = 100 - st.ballOn; entry.fgd = dist;
    if (R() < p) {
      s.score[o] += 3; entry.pts = 3; entry.ptsTeam = o; entry.ev = 'fg';
      entry.text = nm(o, 'K') + ' drills a ' + dist + '-yard field goal. Three points.'; setKick(o, d);
    } else {
      entry.ev = 'fgmiss';
      giveBall(d, Math.max(20, 100 - st.ballOn + 7));
      entry.text = nm(o, 'K') + ' misses from ' + dist + ' yards.';
    }
  } else if (live) {
    // a snap the players actually played out on the field (lib/live.js): the outcome tells where the ball ended up
    const lv = live, qb = nm(o, 'QB');
    pt = clamp(Math.ceil((lv.t || 20) / 20), 1, 8); if (lv.k === 'inc' || lv.oob) stopFlag = true;
    entry.live = true; entry.liveT = lv.t || 0;
    const clampY = y => clamp(Math.round(y), -st.ballOn, 100 - st.ballOn);
    if (lv.k === 'sack') {
      const loss = Math.max(1, Math.round(-lv.x)), who = lv.by ? nm(d, lv.by) : 'The defense'; entry.defId = lv.by; entry.qbId = 'QB';
      entry.anim = 'sack'; entry.travel = -loss; entry.yards = -loss; entry.ev = 'sack';
      const nb = st.ballOn - loss;
      if (nb <= 0) entry.text = safety(who + ' sacks ' + qb + ' in the end zone.');
      else {
        s.ballOn = nb; s.toGo = st.toGo + loss; s.down = st.down + 1;
        entry.text = who + ' sacks ' + qb + ' for a loss of ' + yds(loss) + '.';
        if (s.down > 4) { giveBall(d, 100 - nb); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
      }
    } else if (lv.k === 'inc') {
      const rec = lv.tgt ? nm(o, lv.tgt) : null; entry.qbId = 'QB'; if (lv.tgt) entry.recId = lv.tgt;
      entry.anim = 'inc'; entry.travel = Math.max(2, Math.round(lv.x)); entry.ev = 'inc';
      s.toGo = st.toGo; s.down = st.down + 1; s.ballOn = st.ballOn;
      if (lv.away || !rec) entry.text = qb + ' throws it away.';
      else if (lv.pbu) { entry.defId = lv.pbu; entry.text = qb + "'s pass for " + rec + ' is broken up by ' + nm(d, lv.pbu) + '.'; }
      else if (lv.drop) entry.text = rec + ' drops the pass from ' + qb + '.';
      else entry.text = qb + "'s pass for " + rec + ' falls incomplete.';
      if (s.down > 4) { giveBall(d, 100 - st.ballOn); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
    } else if (lv.k === 'int') {
      const who = nm(d, lv.by); entry.defId = lv.by; entry.qbId = 'QB'; entry.anim = 'int'; entry.ev = 'int'; entry.travel = Math.max(2, Math.round(lv.x));
      const spot = st.ballOn + lv.x;
      if (lv.tdRet) entry.text = scoreTD(d, qb + ' is picked off by ' + who + ', who takes it all the way back!');
      else if (spot >= 100) { giveBall(d, 20); entry.text = qb + ' is picked off in the end zone by ' + who + '. Touchback.'; }
      else { giveBall(d, 100 - (st.ballOn + clamp(lv.retX == null ? lv.x : lv.retX, -st.ballOn + 1, 99 - st.ballOn))); entry.text = qb + ' is picked off by ' + who + '.'; }
    } else if (lv.k === 'fumble') {
      const runner = nm(o, lv.who || 'HB'); entry.defId = lv.by; entry.ev = 'fumble';
      const y = lv.sack ? Math.min(0, clampY(lv.x)) : Math.max(0, clampY(lv.x)); entry.yards = y; entry.travel = y;
      const forcer = lv.by ? nm(d, lv.by) : 'the defense';
      if (lv.sack) { entry.anim = 'sack'; entry.qbId = 'QB'; entry.sacked = 1; entry.text = forcer + ' sacks ' + runner + ' and strips the ball! ' + teams[d].name + ' recover the fumble.'; }
      else if (lv.pass) { entry.anim = 'pass'; entry.qbId = 'QB'; entry.recId = lv.who; entry.text = qb + ' finds ' + runner + ', but ' + forcer + ' knocks it loose and ' + teams[d].name + ' recover.'; }
      else { entry.anim = 'run'; entry.runId = lv.who; entry.text = runner + ' fumbles, forced out by ' + forcer + ', and ' + teams[d].name + ' recover.'; }
      giveBall(d, 100 - Math.max(1, Math.min(st.ballOn + y, 98)));
    } else if (lv.k === 'safety') {
      entry.yards = -st.ballOn; entry.travel = -st.ballOn; entry.ev = 'safety'; entry.anim = 'run';
      entry.text = safety(nm(o, lv.who || 'QB') + ' is tackled in the end zone.');
    } else { // 'run' or 'pass': the ball carrier was brought down (or scored)
      const y = lv.td ? 100 - st.ballOn : clampY(lv.x), who = nm(o, lv.who || 'HB');
      const passed = lv.k === 'pass';
      entry.travel = y;
      let desc;
      if (passed) {
        entry.anim = 'pass'; entry.qbId = 'QB'; entry.recId = lv.who;
        desc = y >= 20 ? qb + ' connects deep with ' + who + ' for ' + yds(y) + '.' : y <= 0 ? qb + ' finds ' + who + (y === 0 ? ' but he is stopped for no gain.' : ' and he is dropped for a loss of ' + yds(y) + '.') : qb + ' finds ' + who + ' for ' + yds(y) + '.';
      } else {
        entry.anim = 'run'; entry.runId = lv.who;
        desc = y <= 0 ? (y === 0 ? who + ' is stuffed for no gain.' : who + ' is dropped for a loss of ' + yds(y) + '.')
             : y >= 15 ? who + ' breaks free for ' + yds(y) + '.' : lv.who === 'QB' ? who + ' scrambles for ' + yds(y) + '.' : who + ' runs for ' + yds(y) + '.';
      }
      if (lv.fum && !lv.td) { entry.fum = 'kept'; entry.defId = lv.fum; desc += ' The ball comes loose but ' + who + ' falls on it.'; }
      entry.text = advance(y, desc);
      if (entry.ev === 'play') entry.ev = passed ? 'pass' : 'run';
    }
    if (lv.fum && !lv.td && (lv.k === 'sack') && entry.ev !== 'fumble') { entry.fum = 'kept'; entry.defId = lv.fum; entry.text += ' The ball comes loose but ' + qb + ' falls on it.'; }
  } else if (OC.kind === 'run') {
    const inside = ocat === 'RUN_IN';
    const m = matchup(defPick, offPick), eff = 1 + 0.30 * m;
    const Orun = (inside ? 0.42 * OU.h + 0.38 * OU.ol + 0.20 * OU.fbq
                         : 0.50 * OU.h + 0.30 * OU.ol + 0.20 * OU.wr) + (inside && OU.hasFB ? 2 : 0);
    const Drun = 0.38 * DU.dl + 0.36 * DU.lb + 0.14 * DU.s + 0.12 * DU.cb + (DU.scheme === '43' ? 3 : 0);
    const diff = Orun - Drun * eff;
    let y = Math.round((inside ? 3.6 : 4.0) + (OC.ym || 0) + diff * 0.10 + gauss() * (inside ? 2.8 : 3.8) * (OC.sd || 1));
    const bigP = (inside ? 0.035 : 0.07) + (OC.bp || 0) + Math.max(0, OU.hSpd - 55) / 700;
    if (R() < bigP * (1 - m * 0.25)) y += Math.round(8 + R() * 20);
    y = Math.max(y, OC.fl == null ? -4 : OC.fl);
    if (OC.sy && st.toGo <= 2 && y < st.toGo && R() < 0.3) y = st.toGo;   // a dive picks up the hard yard
    if (R() < (inside ? 0.03 : 0.2) + (OC.oob || 0)) stopFlag = true;   // ran out of bounds
    const useFB = inside && OU.hasFB && R() < 0.25;
    const runner = nm(o, useFB ? 'FB' : 'HB'); entry.runId = useFB ? 'FB' : 'HB';
    const fumP = 0.046 + (OC.fum || 0) + Math.max(0, DU.dl - OU.ol) * 0.0003;
    const fumbled = R() < fumP, lost = fumbled && R() < 0.5;
    const fid = fumbled ? DU.rushers[Math.floor(R() * DU.rushers.length)] : null;
    if (fid) entry.defId = fid;
    entry.anim = 'run';
    const spot = Math.max(0, st.ballOn + Math.max(0, y));
    if (lost) {
      entry.ev = 'fumble'; entry.yards = Math.max(0, y); entry.travel = Math.max(0, y);
      giveBall(d, 100 - Math.min(spot, 98));
      entry.text = runner + ' fumbles, forced out by ' + nm(d, fid) + ', and ' + teams[d].name + ' recover.';
    } else {
      entry.travel = y;
      let desc;
      if (y <= 0) desc = y === 0 ? runner + ' is stuffed for no gain.' : runner + ' is dropped for a loss of ' + yds(y) + '.';
      else if (y >= 15) desc = runner + ' breaks free for ' + yds(y) + '.';
      else desc = runner + ' runs for ' + yds(y) + '.';
      if (fumbled && spot < 100) { entry.fum = 'kept'; desc += ' The ball comes loose but ' + runner + ' falls on it.'; }
      entry.text = advance(y, desc);
      if (entry.ev === 'play') entry.ev = 'run';
    }
  } else {
    // pass
    const spec = OC;
    const m = matchup(defPick, offPick), eff = 1 + 0.30 * m;
    const rush = 0.6 * DU.dl + 0.4 * DU.lb + (DC.rush || 0) + (DU.scheme === '34' ? 2 : 0);
    const prot = OU.ol;
    const sackP = clamp(0.06 + (rush - prot) * 0.0035 + (DC.sack || 0) + (spec.sack || 0), 0.01, 0.30);
    const pressure = Math.max(0, rush - prot) * 0.0030 + (DC.press || 0);
    const cov = 0.45 * DU.cb + 0.30 * DU.s + 0.25 * DU.lb;
    // target
    let tgt;
    if (spec.hb && R() < spec.hb) tgt = { id: 'HB', fit: OU.h, spd: OU.hSpd };
    else {
      let tot = 0;
      const ws = OU.recv.map(r => {
        let w = Math.pow(r.fit / 100, 2);
        if (spec.spd) w *= Math.pow(r.spd / 60, spec.spd);
        w *= (spec.tw && spec.tw[r.id] != null) ? spec.tw[r.id] : 1;
        tot += w; return w;
      });
      let x = R() * tot; tgt = OU.recv[OU.recv.length - 1];
      for (let i = 0; i < ws.length; i++) { x -= ws[i]; if (x <= 0) { tgt = OU.recv[i]; break; } }
    }
    const qb = nm(o, 'QB'), rec = nm(o, tgt.id); entry.qbId = 'QB'; entry.recId = tgt.id;
    const O = 0.38 * OU.q + 0.42 * tgt.fit + 0.20 * OU.ol + (spec.fbq && !OU.hasFB ? 2 : 0);
    const compP = clamp(spec.base - 0.03 + (O - cov * eff) * 0.0070 - pressure, 0.08, 0.93);   // -0.03: offense tuned a little harder
    const intP = clamp(0.028 + (cov * eff - OU.q) * 0.0012 + (spec.int || 0), 0.006, 0.12);
    const r1 = R();
    if (r1 < sackP) {
      const loss = Math.round(3 + R() * 5 + (DC.loss || 0));
      const wid = DU.rushers[Math.floor(R() * DU.rushers.length)], who = nm(d, wid); entry.defId = wid;
      entry.anim = 'sack'; entry.travel = -loss; entry.yards = -loss; entry.ev = 'sack';
      const nb = st.ballOn - loss;
      const strip = R() < 0.10 + (DC.rush || 0) * 0.004, stripLost = strip && R() < 0.5;
      if (nb <= 0) { entry.text = safety(who + ' sacks ' + qb + ' in the end zone.'); }
      else if (stripLost) {
        entry.ev = 'fumble'; entry.sacked = 1; giveBall(d, 100 - nb);
        entry.text = who + ' sacks ' + qb + ' and strips the ball! ' + teams[d].name + ' recover the fumble.';
      } else {
        s.ballOn = nb; s.toGo = st.toGo + loss; s.down = st.down + 1;
        entry.text = who + ' sacks ' + qb + ' for a loss of ' + yds(loss) + '.';
        if (strip) { entry.fum = 'kept'; entry.text += ' The ball comes loose but ' + qb + ' falls on it.'; }
        if (s.down > 4) { giveBall(d, 100 - nb); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
      }
    } else if (R() < compP) {
      if (R() < (spec.oob == null ? 0.25 : spec.oob)) stopFlag = true;   // caught out of bounds
      let y = Math.round(spec.avg * (0.55 + 0.9 * R()) + (O - cov * eff) * 0.10);
      const bigP = 0.05 + (spec.big || 0) + Math.max(0, tgt.spd - 60) / 500;
      if (R() < bigP) y += Math.round(6 + R() * 18);
      y = clamp(y, 0, 100 - st.ballOn);
      entry.anim = 'pass'; entry.travel = y;
      let desc = y >= 20 ? qb + ' connects deep with ' + rec + ' for ' + yds(y) + '.'
                 : y === 0 ? qb + ' finds ' + rec + ' but he is stopped for no gain.'
                 : qb + ' finds ' + rec + ' for ' + yds(y) + '.';
      const cf = y > 0 && st.ballOn + y < 100 && R() < 0.036 + (DC.rush || 0) * 0.001, cfLost = cf && R() < 0.5;
      if (cfLost) {
        const wid = DU.hawks[Math.floor(R() * DU.hawks.length)]; entry.defId = wid; entry.ev = 'fumble'; entry.yards = y;
        giveBall(d, 100 - Math.min(st.ballOn + y, 98));
        entry.text = qb + ' finds ' + rec + ' for ' + yds(y) + ', but ' + nm(d, wid) + ' rips it out and ' + teams[d].name + ' recover.';
      } else {
        if (cf) { entry.fum = 'kept'; desc += ' The ball comes loose but ' + rec + ' falls on it.'; }
        entry.text = advance(y, desc);
        if (entry.ev === 'play') entry.ev = 'pass';
      }
    } else if (R() < intP / Math.max(0.2, 1 - compP)) {
      const wid = DU.hawks[Math.floor(R() * DU.hawks.length)], who = nm(d, wid); entry.defId = wid;
      entry.anim = 'int'; entry.travel = spec.depth; entry.ev = 'int';
      const spot = st.ballOn + spec.depth;
      if (spot >= 100) { giveBall(d, 20); entry.text = qb + ' is picked off in the end zone by ' + who + '. Touchback.'; }
      else if (R() < 0.04) { entry.text = scoreTD(d, qb + ' is picked off by ' + who + ', who takes it all the way back!'); entry.ev = 'int'; }
      else {
        const ret = Math.round(R() * 14);
        giveBall(d, 100 - spot + ret);
        entry.text = qb + ' is picked off by ' + who + '.';
      }
    } else {
      entry.anim = 'inc'; entry.travel = Math.max(2, spec.depth - 2); entry.ev = 'inc'; stopFlag = true; pt = 3;
      s.toGo = st.toGo; s.down = st.down + 1; s.ballOn = st.ballOn;
      const xi = R(), pAway = clamp(0.05 + pressure * 2.5, 0.03, 0.22), pDrop = clamp(0.11 - (tgt.fit - 60) * 0.002, 0.03, 0.16);
      if (xi < pAway) { delete entry.recId; entry.text = qb + ' throws it away.'; }
      else if (xi < pAway + pDrop) entry.text = rec + ' drops the pass from ' + qb + '.';
      else if (R() < 0.62) {
        const wid = DU.hawks[Math.floor(R() * DU.hawks.length)]; entry.defId = wid; entry.pbu = 1;
        entry.text = qb + "'s pass for " + rec + ' is broken up by ' + nm(d, wid) + '.';
      } else entry.text = qb + "'s pass for " + rec + ' falls incomplete.';
      if (s.down > 4) { giveBall(d, 100 - st.ballOn); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
    }
  }

  // clock + quarters
  s.playNo = st.playNo + 1;
  const changed = s.score.a !== st.score.a || s.score.b !== st.score.b;
  const stops = stopFlag || changed || s.poss !== st.poss;
  const left = s.clock - pt;
  entry.pt = pt;
  if (left > 0) {
    // after the play, if the clock is still running, at most CAP more seconds tick off before the next snap; a quarter never ends between snaps
    const ro = stops ? 0 : Math.min(CAP, left - 1);
    s.clock = left - ro; s.ro = ro;
    if (st.ot && changed) s.over = true;
  } else {
    s.clock = 0; s.ro = 0;
    if (st.ot) s.over = true;
    else if (st.q === 1 || st.q === 3) { s.q = st.q + 1; s.clock = QLEN; entry.qEnd = 'Q' + st.q; entry.text += ' End of the ' + ['', '1st', '2nd', '3rd'][st.q] + ' quarter.'; }
    else if (st.q === 2) { s.q = 3; s.clock = QLEN; s.to = { a: TO_HALF, b: TO_HALF }; entry.half = true; entry.text += ' Halftime.'; setKick(st.firstRecv, other(st.firstRecv)); }
    else if (s.score.a === s.score.b) { s.ot = true; s.q = 5; s.clock = QLEN; s.to = { a: TO_OT, b: TO_OT }; entry.otStart = true; entry.text += ' Tied after four quarters: overtime.'; setKick(other(st.firstRecv), st.firstRecv); }
    else s.over = true;
  }
  if (tos.length) entry.text = tos.map(t => teams[t].name + ' call a timeout. ').join('') + entry.text;
  if (s.over) s.winner = s.score.a > s.score.b ? 'a' : s.score.b > s.score.a ? 'b' : null;
  entry.after = { poss: s.poss, ballOn: s.ballOn, down: s.down, toGo: s.toGo };
  entry.score = { a: s.score.a, b: s.score.b };
  return { state: s, entry };
}

/* ---------- who is on the field (campaign and league squads) ----------
   A squad from a franchise roster carries rot: every running back, receiver and tight end with u, his usage (0-100, set by the coach).
   On each run or pass snap the HB, the two WR spots and the TE spot are filled from it: weighted by usage and by how well the player
   fits the play (speed for deep shots, overall for quick and intermediate routes; on runs speed outside, overall inside), and on
   passing downs a receiver can take the TE spot (the slot). Drawn from the game seed, so every screen and the server agree.
   Squads without rot (the quick game) always play their five. */
const PERS_PASS = { PASS_S: 'quick', SCREEN: 'quick', PASS_M: 'mid', PASS_D: 'deep' };
/* fatigue (squads with a rotation): st.fat[id] is a player's energy, 1 = fresh. Every run or pass snap on the field costs some (backs the
   most), a snap off the field, a kick, a new quarter and halftime give it back. A tired player is drawn less often and plays below his
   rating (up to FAT_DROP points when spent), so the rotation brings in fresher legs as a drive goes on. Part of the game state, so the
   replay, the live sim and the server agree. */
const FAT_COST = { HB: 0.1, WR: 0.05, TE: 0.06 }, FAT_REST = 0.05, FAT_DROP = 14;
const energy = (st, id) => st.fat && st.fat[id] != null ? st.fat[id] : 1;
function fatigueAfter(st, nst, sn, teams, pick) {
  const oc = OFF[pick], play = oc && (oc.kind === 'run' || oc.kind === 'pass');
  const fat = Object.assign({}, st.fat || {}), on = {};
  if (play && sn.on) ['HB', 'WR1', 'WR2', 'TE'].forEach(k => { on[sn.on[k][0]] = 1; });
  const bonus = nst.q !== st.q ? (st.q === 2 ? 0.5 : 0.25) : 0;   // between quarters, and halftime
  ['a', 'b'].forEach(side => {
    const rot = teams[side].squad.rot; if (!rot) return;
    ['HB', 'WR', 'TE'].forEach(pos => (rot[pos] || []).forEach(p => {
      let e = fat[p.i] != null ? fat[p.i] : 1;
      if (side === st.poss && on[p.i]) e -= FAT_COST[pos] * (1.2 - Math.min(0.4, Math.max(0, (p.o - 70) / 75)));   // better conditioned stars tire a little slower
      else e += play ? FAT_REST : FAT_REST * 0.7;
      e = Math.min(1, Math.max(0, e + bonus));
      if (e >= 1) delete fat[p.i]; else fat[p.i] = Math.round(e * 1000) / 1000;
    }));
  });
  nst.fat = fat;
}
function persFit(p, cat, slot) {
  const o = (p.o - 55) / 40, s = ((p.s || 85) - 78) / 18;
  if (cat === 'deep') return Math.max(0.15, 0.35 + 0.35 * o + 0.9 * s);
  if (cat === 'quick') return Math.max(0.15, 0.4 + 0.8 * o + 0.15 * s);
  if (cat === 'mid') return Math.max(0.15, 0.4 + 0.7 * o + 0.3 * s);
  if (cat === 'RUN_OUT') return Math.max(0.15, 0.4 + 0.5 * o + (slot === 'HB' ? 0.6 * s : 0));
  return Math.max(0.15, 0.4 + 0.8 * o);   // inside runs: the best players (and blockers)
}
// n of the list, each in with probability proportional to his weight (at most 1): a systematic draw, so a player's usage is his share of snaps
function persDraw(R, list, n, w) {
  const ws = list.map(p => Math.max(0, w(p))), pr = ws.map(() => 0);
  let left = n, free = list.map((_, i) => i);
  for (let pass = 0; pass < list.length && left > 0 && free.length; pass++) {
    const tot = free.reduce((t, i) => t + ws[i], 0); if (tot <= 0) break;
    const full = free.filter(i => left * ws[i] / tot >= 1);
    if (!full.length) { free.forEach(i => { pr[i] = left * ws[i] / tot; }); break; }
    full.forEach(i => { pr[i] = 1; }); left -= full.length; free = free.filter(i => full.indexOf(i) < 0);
  }
  const out = [], u = R(); let c = 0;
  list.forEach((p, i) => { const a = Math.floor(c + u); c += pr[i]; if (Math.floor(c + u) > a && out.length < n) out.push(p); });
  for (let i = 0; out.length < n && i < list.length; i++) if (out.indexOf(list[i]) < 0) out.push(list[i]);   // (rounding) fill up
  return out;
}
function personnel(sq, st, pick, seed, side) {
  const rot = sq.rot, oc = OFF[pick];
  if (!rot || !oc || (oc.kind !== 'run' && oc.kind !== 'pass')) return sq;
  const R = mulberry32(hashStr(seed + ':pers:' + st.playNo + ':' + side));
  const cat = oc.kind === 'pass' ? PERS_PASS[oc.cat] || 'mid' : oc.cat;
  const en = p => energy(st, p.i), use = p => (p.u == null ? 50 : p.u) / 100 * (0.35 + 0.65 * en(p));   // tired players sit a little more often
  const hb = rot.HB && rot.HB.length ? persDraw(R, rot.HB, 1, p => use(p) * persFit(p, cat, 'HB'))[0] : sq.hb;
  const wrs = rot.WR && rot.WR.length >= 2 ? persDraw(R, rot.WR, 2, p => use(p) * persFit(p, cat, 'WR')) : sq.wr;
  // the TE spot: a tight end, or on passing downs (or deep shots) a third receiver in the slot
  const slotish = oc.kind === 'pass' && (st.toGo >= 7 || st.down === 3 || cat === 'deep') ? 0.5 : 0.05;
  const yc = (rot.TE || []).map(p => ({ p, w: use(p) * persFit(p, cat, 'TE') })).concat((rot.WR || []).filter(p => wrs.indexOf(p) < 0).map(p => ({ p, w: use(p) * persFit(p, cat, 'WR') * slotish })));
  const te = yc.length ? persDraw(R, yc, 1, x => x.w)[0].p : sq.te;
  const tired = p => { const e = en(p); return e >= 0.999 ? p : Object.assign({}, p, { o: Math.round(p.o - (1 - e) * FAT_DROP), e: Math.round(e * 100) }); };   // and play below their rating
  return Object.assign({}, sq, { hb: tired(hb), wr: [tired(wrs[0]), tired(wrs[1])], te: tired(te) });
}
// the teams for one snap: the offense with this snap's personnel; U for the offense worked out again when it changed
function snapTeams(teams, U, st, pick, seed, cache) {
  const off = st.poss, sq = teams[off].squad;
  if (!sq.rot) return { teams, U, on: null };
  const ps = personnel(sq, st, pick, seed, off);
  if (ps === sq) return { teams, U, on: null };
  const key = off + [ps.hb, ps.wr[0], ps.wr[1], ps.te].map(p => p.i + ':' + p.o).join(',');
  const t2 = Object.assign({}, teams, { [off]: Object.assign({}, teams[off], { squad: ps }) });
  const uo = cache[key] || (cache[key] = teamUnits(t2[off]));
  const ent = p => [p.i, p.n, p.e != null ? p.e : 100];   // [id, name, energy %]
  const on = { QB: ent(ps.qb), HB: ent(ps.hb), WR1: ent(ps.wr[0]), WR2: ent(ps.wr[1]), TE: ent(ps.te) };
  return { teams: t2, U: Object.assign({}, U, { [off]: uo }), on };
}
function replay(seed, teams, moves, cpuSides) {
  cpuSides = cpuSides || [];
  let st = initState(seed);
  const log = [];
  const U = { a: teamUnits(teams.a), b: teamUnits(teams.b) }, pcache = {};
  let guard = 0, wait = null;
  while (!st.over && guard++ < 320) {
    const n = st.playNo, off = st.poss, def = off === 'a' ? 'b' : 'a';
    let om = moves[n + '-' + off];
    if (!om && cpuSides.indexOf(off) >= 0) om = { pick: cpuMove(st, U, off, seed, 'off'), to: cpuTO(st, off) ? 1 : 0 };
    if (!om) break;
    const kick = noDef(legalOff(st, om.pick));
    let dm = moves[n + '-' + def];
    if (!dm && !kick && cpuSides.indexOf(def) >= 0) dm = { pick: cpuMove(st, U, def, seed, 'def'), to: cpuTO(st, def) ? 1 : 0 };
    if (!kick && !dm) break;
    const sn = snapTeams(teams, U, st, legalOff(st, om.pick), seed, pcache);   // this snap's personnel (campaign and league squads)
    let lv = null;
    if (!kick && ((om.ctl ? 1 : 0) || (dm && dm.ctl ? 1 : 0))) {
      // somebody plays this snap on the field: it is decided by their recorded inputs (replay waits until they are in)
      const lm = moves[n + '-lv'];
      if (!lm || !E.LIVE) { wait = { n, off, def, om, dm }; break; }
      lv = liveOutcome(seed, n, st, legalOff(st, om.pick), DEF_CALLS[dm.pick] ? dm.pick : 'ZONE', sn.teams[off], sn.teams[def], om.ctl ? 1 : 0, dm.ctl ? 1 : 0, lm[off], lm[def]);
    }
    const fl = { o: !!om.to, d: !!(dm && dm.to) };
    let res = stepGame(st, sn.teams, sn.U, seed, om.pick, dm ? dm.pick : null, lv, fl);
    const ro = res.entry.retOpp;
    if (ro && E.LIVE && cpuSides.indexOf(ro.recv) < 0 && lastCtl(moves, ro.recv, kick ? n - 1 : n)) {   // (on a kick the receiver has not necessarily made a move yet: go by his earlier ones)
      // the receiving player runs the kick back himself: replay waits for his inputs
      const rm = moves[n + '-rv'];
      if (!rm) { wait = { n, kind: 'ret', ro, off, def, om, dm }; break; }
      const rv = retOutcome(seed, n, ro, teams[ro.recv], teams[ro.kicker], rm.ev);
      res = stepGame(st, teams, U, seed, om.pick, dm ? dm.pick : null, lv, fl, rv);
    }
    if (lv) res.entry.ctl = { o: om.ctl ? 1 : 0, d: dm && dm.ctl ? 1 : 0 };
    if (sn.on) res.entry.on = sn.on;   // who played the snap: [id, name] per offensive spot
    if (teams.a.squad.rot || teams.b.squad.rot) fatigueAfter(st, res.state, sn, teams, legalOff(st, om.pick));
    st = res.state; log.push(res.entry);
  }
  return { state: st, log, U, wait };
}
/* ---------- box score: team totals and the players who mattered, straight from the play log ---------- */
function boxScore(log, teams) {
  const mk = () => ({ pts: 0, first: 0, rush: 0, ratt: 0, pass: 0, comp: 0, att: 0, sacksBy: 0, sackYds: 0, to: 0, fumLost: 0, ints: 0, punts: 0, puntYds: 0, plays: 0, pbu: 0, ff: 0 });
  const tm = { a: mk(), b: mk() }, pl = { a: {}, b: {} }, ps = { a: {}, b: {} };
  const P0 = (side, key, slot, name) => { const m = pl[side]; return m[key] || (m[key] = { slot, name: name || nameOf(teams[side], slot), ratt: 0, ryd: 0, rtd: 0, c: 0, a: 0, pyd: 0, ptd: 0, int: 0, rec: 0, recyd: 0, rectd: 0, tgt: 0, sk: 0, dint: 0, pbu: 0, ff: 0, fgm: 0, fga: 0, fgl: 0, xp: 0 }); };
  let cur = null;   // with rotating personnel the log names who was on the field: credit him, not the spot
  const P = (side, slot) => { const w = cur && side === cur.off && cur.on && cur.on[slot]; return w ? P0(side, w[0], slot, w[1]) : P0(side, slot, slot); };
  const o2 = s => s === 'a' ? 'b' : 'a';
  (log || []).forEach(e => {
    cur = e;
    const O = e.off, D = o2(O), t = tm[O], d = tm[D], td = e.ev === 'td';
    if (e.ptsTeam) tm[e.ptsTeam].pts += e.pts || 0;
    if (KICKS[e.offPick]) return;   // kickoffs: the points above are all that count
    if (e.anim === 'fg') { const k = P(O, 'K'); k.fga++; if (e.ev === 'fg') { k.fgm++; k.fgl = Math.max(k.fgl, e.fgd || 0); } return; }
    if (e.anim === 'punt') { t.punts++; t.puntYds += e.travel || 0; if (e.ev === 'fumble') { t.to++; t.fumLost++; } return; }
    if (e.anim === 'spike' || e.anim === 'kneel') return;
    t.plays++;
    if (e.firstDown) t.first++;
    const lost = e.ev === 'fumble';
    if (e.anim === 'run' && e.runId) {
      const r = P(O, e.runId === 'FB' ? 'HB' : e.runId); r.ratt++; r.ryd += e.yards || 0; t.ratt++; t.rush += e.yards || 0; if (td) r.rtd++;
    } else if (e.qbId) {
      const q = P(O, 'QB');
      if (e.anim === 'sack' || e.sacked) { t.sackYds += e.yards || 0; d.sacksBy++; if (e.defId) P(D, e.defId).sk++; }
      else if (e.anim === 'int') { q.a++; q.int++; t.att++; t.ints++; if (e.defId) P(D, e.defId).dint++; }
      else if (e.recId && e.anim === 'inc') {
        q.a++; t.att++; P(O, e.recId).tgt++;
        if (e.pbu || e.defId) { d.pbu++; if (e.defId) P(D, e.defId).pbu++; }
      } else if (e.recId && e.anim === 'pass') {
        q.a++; q.c++; q.pyd += e.yards || 0; t.att++; t.comp++; t.pass += e.yards || 0;
        const rc = P(O, e.recId); rc.rec++; rc.recyd += e.yards || 0; rc.tgt++; if (td) { q.ptd++; rc.rectd++; }
      }
    }
    if (lost) { t.fumLost++; t.to++; d.ff++; if (e.defId) P(D, e.defId).ff++; }
    else if (e.fum === 'kept' && e.defId) { d.ff++; P(D, e.defId).ff++; }
    if (e.anim === 'int') t.to++;
  });
  tm.a.total = tm.a.rush + tm.a.pass + tm.a.sackYds; tm.b.total = tm.b.rush + tm.b.pass + tm.b.sackYds;
  const top = (side, key, n, f) => Object.values(pl[side]).filter(f || (p => p[key] > 0)).sort((x, y) => y[key] - x[key]).slice(0, n);
  const leaders = side => ({
    passing: top(side, 'a', 1, p => p.a > 0),
    rushing: top(side, 'ryd', 2, p => p.ratt > 0),
    receiving: top(side, 'recyd', 3, p => p.rec > 0),
    defense: Object.values(pl[side]).map(p => Object.assign({ pts: p.sk * 3 + p.dint * 4 + p.pbu * 1.5 + p.ff * 2 }, p)).filter(p => p.pts > 0).sort((x, y) => y.pts - x.pts).slice(0, 3),
    kicking: top(side, 'fga', 1, p => p.fga > 0)
  });
  return { teams: tm, lead: { a: leaders('a'), b: leaders('b') } };
}
// does this side run its own players? (its latest recorded move decides: the same rule on every screen and on the server)
function lastCtl(moves, side, n) {
  for (let k = n; k >= 0; k--) { const m = moves[k + '-' + side]; if (m) return !!m.ctl; }
  return false;
}
function retOutcome(seed, n, ro, RT, KT, trace) {
  const key = ['ret', seed, n, ro.kind, ro.at, RT.name, KT.name, (trace || []).join(',')].join('|');
  let o = LCACHE.get(key);
  if (!o) {
    o = E.LIVE.run({ seed, playNo: n, ret: { kind: ro.kind }, ballOn: ro.at, toGo: 10, OS: RT.squad, DS: KT.squad, ctlO: true, ctlD: false }, trace, []).out;
    if (LCACHE.size > 600) LCACHE.clear();
    LCACHE.set(key, o);
  }
  return Object.assign({ kind: ro.kind }, o);
}
const LCACHE = new Map();
function liveOutcome(seed, n, st, offPick, defPick, OT, DT, ctlO, ctlD, trO, trD) {
  const key = [seed, n, st.ballOn, st.toGo, offPick, defPick, OT.name, DT.name, ctlO, ctlD, (trO || []).join(','), (trD || []).join(',')].join('|');
  let o = LCACHE.get(key);
  if (!o) {
    o = E.LIVE.run({ seed, playNo: n, ballOn: st.ballOn, toGo: st.toGo, offPick, defPick, OS: OT.squad, DS: DT.squad, ctlO: !!ctlO, ctlD: !!ctlD }, trO, trD).out;
    if (LCACHE.size > 600) LCACHE.clear();
    LCACHE.set(key, o);
  }
  return Object.assign({}, o);
}
// moves arriving from a client: "n-a"/"n-b" picks (only the sender's side) and "n-lv" input traces of snaps played on the field
function cleanTrace(a) {
  if (a === undefined || a === null) return [];
  if (!Array.isArray(a) || a.length > 500) return null;
  for (let i = 0; i < a.length; i++) if (!Number.isInteger(a[i]) || a[i] < 0 || a[i] > 40000) return null;
  return a;
}
function cleanMoves(raw, side) {
  const mv = {};
  Object.keys(raw || {}).forEach(k => {
    const m = /^(\d{1,3})-(a|b|lv|rv)$/.exec(k); const v = raw[k]; if (!m || !v || typeof v !== 'object') return;
    if (m[2] === 'rv') { const ev = cleanTrace(v.ev); if (ev && (v.s === 'a' || v.s === 'b') && (!side || v.s === side)) mv[k] = { s: v.s, ev }; return; }
    if (m[2] === 'lv') { const a = cleanTrace(v.a), b = cleanTrace(v.b); if (a && b) mv[k] = { a, b }; return; }
    if (side && m[2] !== side) return;
    if (typeof v.pick === 'string' && v.pick.length <= 12) { mv[k] = { pick: v.pick }; if (v.ctl) mv[k].ctl = 1; if (v.to) mv[k].to = 1; }
  });
  return mv;
}
// deterministic CPU decisions so a server can re-verify any game
function cpuMove(st, U, side, seed, role) {
  const rnd = mulberry32(hashStr(seed + ':cpu:' + st.playNo + ':' + side));
  if (st.kick) return cpuKick(st, side, rnd);
  return role === 'off' ? cpuOffense(st, U, side, rnd) : cpuDefense(st, rnd);
}

/* ================= CPU opponent ================= */
// the computer onside kicks when it is behind late in the fourth quarter
function cpuKick(st, me, rnd) {
  if (st.ot || st.q !== 4) return 'KO';
  const lead = st.score[me] - st.score[oth(me)];
  if (lead >= 0 || lead < -16) return 'KO';
  return st.clock <= 100 && rnd() < (st.clock <= 60 ? 0.95 : 0.6) ? 'ONSIDE' : 'KO';
}
// the computer calls a timeout when the clock matters and it is behind (or tied with the ball)
function cpuTO(st, me) {
  if (!(st.ro > 0) || !(st.to[me] > 0) || st.ot) return false;
  const lead = st.score[me] - st.score[oth(me)];
  if (st.q === 2) return st.clock <= 30 && (st.poss === me ? lead <= 7 : lead < 0);
  if (st.q === 4) return st.poss === me ? lead <= 0 && st.clock <= 45 : lead < 0 && st.clock <= 70;
  return false;
}
function cpuOffCat(st, U, me, rnd) {
  const OU = U[me];
  const lead = st.score[me] - st.score[oth(me)];
  if (st.q === 4 && !st.ot && lead > 0 && st.down <= 3 && st.clock <= (CAP + 3) * (4 - st.down)) return 'KNEEL';
  if (!st.ot && (st.q === 2 || (st.q === 4 && lead <= 0)) && st.ro > 0 && st.down <= 3 && st.clock <= 12 && fgDist(st) <= 50) return 'SPIKE';
  if (!st.ot && (st.q === 2 || (st.q === 4 && lead < 0)) && st.clock <= 40 && st.down < 4 && fgDist(st) > 20) return ['PASS_S', 'PASS_M', 'PASS_M', 'PASS_D'][Math.floor(rnd() * 4)];
  if (st.down === 4) {
    const dist = fgDist(st);
    if (dist <= 48 && rnd() < 0.9) return 'FG';
    if (st.toGo <= 2 && st.ballOn > 45 && rnd() < 0.6) return 'RUN_IN';
    if (st.ballOn < 62) return 'PUNT';
    if (dist <= 62 && rnd() < 0.5) return 'FG';
  }
  const passBias = clamp(0.5 + (OU.q + OU.wr - OU.h - OU.ol) * 0.004, 0.3, 0.7);
  if (st.toGo >= 8) return rnd() < passBias + 0.15 ? (rnd() < 0.5 ? 'PASS_M' : rnd() < 0.5 ? 'PASS_D' : 'PASS_S') : 'RUN_OUT';
  if (rnd() < passBias) { const x = rnd(); return x < 0.35 ? 'PASS_S' : x < 0.65 ? 'PASS_M' : x < 0.85 ? 'PASS_D' : 'SCREEN'; }
  return rnd() < 0.6 ? 'RUN_IN' : 'RUN_OUT';
}
function cpuDefCat(st, rnd) {
  const x = rnd();
  if (st.toGo <= 3) return x < 0.45 ? 'STACK' : x < 0.7 ? 'BLITZ' : x < 0.85 ? 'MAN' : 'ZONE';
  if (st.toGo >= 9) return x < 0.35 ? 'ZONE' : x < 0.55 ? 'PREVENT' : x < 0.8 ? 'MAN' : 'BLITZ';
  return x < 0.3 ? 'ZONE' : x < 0.5 ? 'MAN' : x < 0.7 ? 'STACK' : x < 0.9 ? 'BLITZ' : 'PREVENT';
}

// pick one of the plays in a category, weighted by the situation and by what the team is good at
function pickWeighted(ids, w, rnd) {
  let tot = 0; const ws = ids.map(id => { const v = Math.max(0, w[id] == null ? 1 : w[id]); tot += v; return v; });
  let x = rnd() * tot;
  for (let i = 0; i < ids.length; i++) { x -= ws[i]; if (x <= 0) return ids[i]; }
  return ids[ids.length - 1];
}
function cpuOffense(st, U, me, rnd) {
  rnd = rnd || Math.random;
  const c = cpuOffCat(st, U, me, rnd), OU = U[me];
  if (OFF[c].cat === 'SPEC') return c;
  const ids = Object.keys(OFF).filter(id => OFF[id].cat === c);
  const short = st.toGo <= 2, long = st.toGo >= 7, late = st.q === 4 && st.clock <= 60 && st.score[me] < st.score[oth(me)];
  const w = {
    DIVE: short ? 4 : 0.15, DRAW: long ? 1.3 : 0.5, POWER: 1, SWEEP: short ? 0.2 : 0.8, COUNTER: 0.9,
    HITCH: st.toGo <= 5 ? 1.5 : 0.8, MESH: 1.2, STICK: OU.recv[2].fit >= 78 ? 1.6 : 0.7,
    CURLS: st.toGo <= 10 ? 1.2 : 0.8, FLOOD: 1, YCROSS: OU.recv[2].fit >= 78 ? 1.4 : 0.8,
    POST: 1.2, GO: late ? 1.6 : 0.6, PA_DEEP: OU.h + OU.ol >= 150 ? 1.2 : 0.5,
    BUBBLE: 1, TUNNEL: 1
  };
  return pickWeighted(ids, w, rnd);
}
function cpuDefense(st, rnd) {
  rnd = rnd || Math.random;
  const c = cpuDefCat(st, rnd), ids = Object.keys(DEF_CALLS).filter(id => DEF_CALLS[id].cat === c);
  const goal = st.ballOn >= 93, longs = st.toGo >= 9, endgame = st.q === 4 && st.clock <= 45;
  const w = { STACK: goal ? 0.6 : 1, GOALLINE: goal ? 4 : 0, RUNBLITZ: 0.8, ZONE: 1, COV3: 1, COV4: longs ? 1.6 : 0.8, MAN: 1, MAN2: 0.7, TIGHT: goal ? 1.5 : 0.5,
              BLITZ: 0.6, ZBLITZ: 1, CBBLITZ: 0.7, PREVENT: endgame ? 3 : 0.6, SOFT: endgame ? 0.5 : 1 };
  return pickWeighted(ids, w, rnd);
}

