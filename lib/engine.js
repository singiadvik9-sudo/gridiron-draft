/* ================= draft ================= */
function drawOptions(picks, slotIdx, rnd) {
  rnd = rnd || Math.random;
  const kind = SLOTS[slotIdx].kind, isU = kind === 'OL' || kind === 'DEF';
  const used = {};
  picks.forEach((id, i) => { const k = SLOTS[i].kind; used[(k === 'WR' ? 'WR' : k) + ':' + id] = 1; });
  const pk = kind === 'WR' ? 'WR' : kind;
  const pool = POOLS[pk].filter(c => !used[pk + ':' + c.id]);
  const pick = () => pool.splice(Math.floor(rnd() * pool.length), 1)[0];
  const opts = [pick(), pick(), pick()];
  const floor = isU ? 80 : 78;
  for (let t = 0; t < 6 && Math.max.apply(null, opts.map(c => c.ovr)) < floor; t++) opts[Math.floor(rnd() * 3)] = pick();
  return opts.map(c => c.id);
}
function autoDraft(rnd) {
  rnd = rnd || Math.random;
  const roster = [];
  SLOTS.forEach((s, i) => {
    const opts = drawOptions(roster, i, rnd);
    opts.sort((a, b) => ovrOf(i, b) - ovrOf(i, a));
    roster.push(opts[0]);
  });
  return withReturner(roster);
}

