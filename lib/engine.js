/* ================= constants ================= */
const PQ = 16;          // plays per quarter
const OT_MAX = 8;       // overtime play cap (sudden death)

function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
function hashStr(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

/* ================= league data ================= */
// DATA is generated by build_data.py: 160 skill players, 32 O-line packages, 32 defense packages.
const D = root.DATA || require('./data.json');
const TEAMS = D.TEAMS, PLAYERS = D.PLAYERS, OLU = D.OLU, DFU = D.DFU;
const TIDX = {}; TEAMS.forEach((t, i) => { TIDX[t.abbr] = i; });
const avgOf = (a, f) => a.reduce((t, x) => t + f(x), 0) / a.length;
const GROUPS = ['DL', 'LB', 'CB', 'S'];
// pro ratings (60-99) are stretched onto the scale the play engine was tuned on
const FIT_BASE = 60;
function fit(ovr) { return clamp(Math.round(FIT_BASE + (ovr - 83) * 1.35), 20, 96); }          // individual players
function fitU(ovr) { return clamp(Math.round(FIT_BASE + (ovr - 79) * 2.2), 20, 96); }         // averaged packages
function grade(o) { return o >= 90 ? 'S' : o >= 82 ? 'A' : o >= 74 ? 'B' : o >= 66 ? 'C' : 'D'; }

OLU.forEach((u, i) => { u.id = i; u.ovr = Math.round(avgOf(u.players, p => p[1])); u.tm = TEAMS[TIDX[u.team]]; });
DFU.forEach((u, i) => {
  u.id = i; u.tm = TEAMS[TIDX[u.team]];
  u.g = {};
  GROUPS.forEach(g => { u.g[g] = avgOf(u.players.filter(p => p[1] === g), p => p[3]); });
  u.ovr = Math.round(0.30 * u.g.DL + 0.25 * u.g.LB + 0.25 * u.g.CB + 0.20 * u.g.S);
});
PLAYERS.forEach(p => { p.tm = TEAMS[TIDX[p.team]]; });

/* ================= slots (7 rounds) ================= */
const SLOTS = [
  { id: 'QB',  kind: 'QB',  label: 'Quarterback',   short: 'QB' },
  { id: 'HB',  kind: 'HB',  label: 'Running Back',  short: 'HB' },
  { id: 'WR1', kind: 'WR',  label: 'Wide Receiver', short: 'WR' },
  { id: 'WR2', kind: 'WR',  label: 'Wide Receiver', short: 'WR' },
  { id: 'TE',  kind: 'TE',  label: 'Tight End',     short: 'TE' },
  { id: 'OL',  kind: 'OL',  label: 'Offensive Line', short: 'OL' },
  { id: 'DEF', kind: 'DEF', label: 'Defense',       short: 'DEF' }
];
function buildSlots() { return SLOTS; }
const poolOf = kind => kind === 'OL' ? OLU : kind === 'DEF' ? DFU : PLAYERS.filter(p => p.pos === kind);
const POOLS = {}; ['QB', 'HB', 'WR', 'TE', 'OL', 'DEF'].forEach(k => { POOLS[k] = poolOf(k); });
function entity(slotIdx, id) {
  const k = SLOTS[slotIdx].kind;
  return k === 'OL' ? OLU[id] : k === 'DEF' ? DFU[id] : PLAYERS[id];
}
function ovrOf(slotIdx, id) { return entity(slotIdx, id).ovr; }
function validRoster(r) {
  return Array.isArray(r) && r.length === SLOTS.length && r.every((id, i) => {
    if (!Number.isInteger(id) || id < 0) return false;
    const k = SLOTS[i].kind;
    return k === 'OL' ? id < OLU.length : k === 'DEF' ? id < DFU.length : (id < PLAYERS.length && PLAYERS[id].pos === k);
  }) && r[2] !== r[3];
}
function unitName(u, kind) { return u.tm.nick + (kind === 'OL' ? ' O-Line' : ' Defense'); }
function teamLabel(r) { // short label for a roster, e.g. the QB's franchise
  return PLAYERS[r[0]].tm.nick;
}

/* ================= squads =================
   A squad is the JSON snapshot of who plays for a side:
   { tm, qb, hb, wr:[a,b], te, ol:{tm,p:[[name,ovr,id]x5]}, df:{tm,sch,p:[[pos,grp,name,ovr,id]x11]} }
   skill player: { i,n,o,s,sk,hr,tm }  (id, name, overall, speed, skin, hair, franchise abbr) */
const skillOf = p => ({ i: 'p' + p.id, n: p.name, o: p.ovr, s: p.spd, sk: p.skin, hr: p.hair, tm: p.team });
function squadFromRoster(r) {
  const ol = OLU[r[5]], df = DFU[r[6]];
  return {
    tm: PLAYERS[r[0]].team,
    qb: skillOf(PLAYERS[r[0]]), hb: skillOf(PLAYERS[r[1]]), wr: [skillOf(PLAYERS[r[2]]), skillOf(PLAYERS[r[3]])], te: skillOf(PLAYERS[r[4]]),
    ol: { tm: ol.team, p: ol.players.map((p, i) => [p[0], p[1], 'o' + ol.id + '_' + i]) },
    df: { tm: df.team, sch: df.scheme, p: df.players.map((p, i) => [p[0], p[1], p[2], p[3], 'd' + df.id + '_' + i]) }
  };
}
function mkTeam(name, roster) { return { name, squad: squadFromRoster(roster) }; }
const gAvg = (p, g, k) => { const a = p.filter(x => x[1] === g); return a.reduce((t, x) => t + x[k], 0) / a.length; };
function packRatings(sq) {
  const olo = Math.round(avgOf(sq.ol.p, p => p[1]));
  const g = {}; GROUPS.forEach(k => { g[k] = gAvg(sq.df.p, k, 3); });
  return { ol: olo, g, def: Math.round(0.30 * g.DL + 0.25 * g.LB + 0.25 * g.CB + 0.20 * g.S) };
}
function teamUnits(team) {
  const sq = team.squad, pr = packRatings(sq);
  const P = [sq.qb, sq.hb, sq.wr[0], sq.wr[1], sq.te];
  const f = { QB: fit(P[0].o), HB: fit(P[1].o), WR1: fit(P[2].o), WR2: fit(P[3].o), TE: fit(P[4].o) };
  const sp = i => P[i].s - 22;
  const U = {
    f, q: f.QB, h: f.HB, te: f.TE, fbq: f.TE, hasFB: false, scheme: sq.df.sch,
    wr: (f.WR1 + f.WR2) / 2, ol: fitU(pr.ol),
    dl: fitU(pr.g.DL), lb: fitU(pr.g.LB), cb: fitU(pr.g.CB), s: fitU(pr.g.S), k: 72,
    hSpd: sp(1),
    recv: [{ id: 'WR1', fit: f.WR1, spd: sp(2) }, { id: 'WR2', fit: f.WR2, spd: sp(3) }, { id: 'TE', fit: f.TE, spd: sp(4) }],
    rushers: [], hawks: []
  };
  sq.df.p.forEach((p, i) => { if (p[1] === 'DL' || p[1] === 'LB') U.rushers.push('D' + i); else U.hawks.push('D' + i); });
  const o = i => P[i].o;
  U.offR = Math.round(.25 * o(0) + .12 * o(1) + .20 * (o(2) + o(3)) / 2 + .08 * o(4) + .35 * pr.ol);
  U.defR = pr.def; U.ovrR = Math.round((U.offR + U.defR) / 2);
  U.off = Math.round(.25 * U.q + .12 * U.h + .20 * U.wr + .08 * U.te + .35 * U.ol);
  U.def = Math.round(.30 * U.dl + .25 * U.lb + .25 * U.cb + .20 * U.s);
  U.ovr = Math.round((U.off + U.def) / 2);
  return U;
}
function nameOf(team, id) {
  const sq = team.squad;
  switch (id) {
    case 'QB': return sq.qb.n;
    case 'HB': case 'FB': return sq.hb.n;
    case 'WR1': return sq.wr[0].n;
    case 'WR2': return sq.wr[1].n;
    case 'TE': return sq.te.n;
    case 'K': return (TEAMS[TIDX[sq.tm]] || { nick: 'Team' }).nick + ' kicker';
    default: if (id[0] === 'D') return sq.df.p[+id.slice(1)][2]; return id;
  }
}
// player id (for stat keeping) behind a role id
function idOf(team, id) {
  const sq = team.squad;
  switch (id) {
    case 'QB': return sq.qb.i; case 'HB': return sq.hb.i; case 'WR1': return sq.wr[0].i; case 'WR2': return sq.wr[1].i; case 'TE': return sq.te.i;
    default: return id[0] === 'D' ? sq.df.p[+id.slice(1)][4] : null;
  }
}

/* ================= draft ================= */
function drawOptions(picks, slotIdx, rnd) {
  rnd = rnd || Math.random;
  const kind = SLOTS[slotIdx].kind, isU = kind === 'OL' || kind === 'DEF';
  const used = {};
  picks.forEach((id, i) => { const k = SLOTS[i].kind; used[(k === 'WR' ? 'WR' : k) + ':' + id] = 1; });
  const pk = kind === 'WR' ? 'WR' : kind;
  const pool = POOLS[pk].filter(c => !used[pk + ':' + c.id]);
  const pick = () => pool.splice(Math.floor(rnd() * pool.length), 1)[0];
  const opts = [pick(), pick(), pick()];
  const floor = isU ? 80 : 78;
  for (let t = 0; t < 6 && Math.max.apply(null, opts.map(c => c.ovr)) < floor; t++) opts[Math.floor(rnd() * 3)] = pick();
  return opts.map(c => c.id);
}
function autoDraft(rnd) {
  rnd = rnd || Math.random;
  const roster = [];
  SLOTS.forEach((s, i) => {
    const opts = drawOptions(roster, i, rnd);
    opts.sort((a, b) => ovrOf(i, b) - ovrOf(i, a));
    roster.push(opts[0]);
  });
  return roster;
}

/* ================= play calling ================= */
const OFF = {
  RUN_IN:  { label: 'Inside Run',  kind: 'run',  desc: 'Between the tackles. Steady yards, low risk.' },
  RUN_OUT: { label: 'Outside Run', kind: 'run',  desc: 'Bounce it wide. Bigger gains, bigger stuffs.' },
  PASS_S:  { label: 'Quick Pass',  kind: 'pass', depth: 6,  base: 0.79, avg: 6,  desc: 'Short and safe. Beats the blitz.' },
  PASS_M:  { label: 'Medium Pass', kind: 'pass', depth: 13, base: 0.67, avg: 12, desc: 'Intermediate routes. Moves the chains.' },
  PASS_D:  { label: 'Deep Shot',   kind: 'pass', depth: 28, base: 0.45, avg: 28, desc: 'Go for the big play. Risk of a pick.' },
  SCREEN:  { label: 'Screen Pass', kind: 'pass', depth: 2,  base: 0.86, avg: 5,  desc: 'Let the rush come, then dump it off.' },
  PUNT:    { label: 'Punt',        kind: 'kick', desc: 'Flip the field. 4th down only.' },
  FG:      { label: 'Field Goal',  kind: 'kick', desc: 'Kick for three. 4th down, inside 45.' }
};
const DEF_CALLS = {
  STACK:   { label: 'Stack the Box', desc: 'Load up against the run.' },
  ZONE:    { label: 'Zone Shell',    desc: 'Drop into zones. Guards the middle and deep.' },
  MAN:     { label: 'Press Man',     desc: 'Cover tight. Shuts quick and medium routes.' },
  BLITZ:   { label: 'All-Out Blitz', desc: 'Send the house. Sacks, but burns you deep.' },
  PREVENT: { label: 'Prevent',       desc: 'Everyone deep. Gives up short yardage.' }
};
const MATCH = {
  STACK:   { RUN_IN: 1.0, RUN_OUT: .5,  PASS_S: -.3, PASS_M: -.6, PASS_D: -.8, SCREEN: -.2 },
  ZONE:    { RUN_IN: -.3, RUN_OUT: -.2, PASS_S: -.2, PASS_M: .4,  PASS_D: .5,  SCREEN: .1 },
  MAN:     { RUN_IN: 0,   RUN_OUT: -.2, PASS_S: .5,  PASS_M: .3,  PASS_D: -.5, SCREEN: -.5 },
  BLITZ:   { RUN_IN: .4,  RUN_OUT: 0,   PASS_S: .5,  PASS_M: .2,  PASS_D: -.4, SCREEN: -.8 },
  PREVENT: { RUN_IN: -.8, RUN_OUT: -.6, PASS_S: -.4, PASS_M: .2,  PASS_D: .9,  SCREEN: -.4 }
};

function fgDist(st) { return 100 - st.ballOn + 17; }
function legalOff(st, pick) {
  if (!OFF[pick]) return 'RUN_IN';
  if ((pick === 'PUNT' || pick === 'FG') && st.down < 4) return 'RUN_IN';
  if (pick === 'FG' && fgDist(st) > 62) return 'PUNT';
  return pick;
}
function offOptions(st) {
  return Object.keys(OFF).map(id => {
    let disabled = false, note = '';
    if ((id === 'PUNT' || id === 'FG') && st.down < 4) { disabled = true; note = '4th down'; }
    if (id === 'FG' && fgDist(st) > 62) { disabled = true; note = 'Out of range'; }
    if (id === 'FG' && !disabled) note = fgDist(st) + ' yds';
    return { id, label: OFF[id].label, desc: OFF[id].desc, disabled, note };
  });
}

/* ================= game state ================= */
function initState(seed) {
  const firstRecv = (seed % 2 === 0) ? 'a' : 'b';
  return { poss: firstRecv, firstRecv, ballOn: 25, down: 1, toGo: 10, score: { a: 0, b: 0 },
           playNo: 0, over: false, winner: null, ot: false };
}
function clockInfo(st) {
  if (st.ot) return { q: 'OT', inQ: st.playNo - 4 * PQ + 1, perQ: OT_MAX };
  const q = Math.min(4, Math.floor(st.playNo / PQ) + 1);
  return { q: 'Q' + q, inQ: (st.playNo % PQ) + 1, perQ: PQ };
}

function stepGame(st, teams, U, seed, offPickRaw, defPickRaw) {
  const R = mulberry32(hashStr(seed + ':' + st.playNo));
  const gauss = () => (R() + R() + R() + R() - 2) * 1.7320508;
  const o = st.poss, d = o === 'a' ? 'b' : 'a';
  const OU = U[o], DU = U[d];
  const offPick = legalOff(st, offPickRaw);
  const isKick = OFF[offPick].kind === 'kick';
  const defPick = DEF_CALLS[defPickRaw] ? defPickRaw : 'ZONE';
  const s = Object.assign({}, st, { score: { a: st.score.a, b: st.score.b } });
  const nm = (t, id) => nameOf(teams[t], id);
  const entry = {
    n: st.playNo, off: o, offPick, defPick: isKick ? null : defPick, ev: 'play', text: '',
    yards: 0, travel: 0, anim: 'run', pts: 0, ptsTeam: null,
    before: { poss: o, ballOn: st.ballOn, down: st.down, toGo: st.toGo }
  };
  const giveBall = (team, on) => {
    s.poss = team; s.ballOn = clamp(Math.round(on), 1, 99); s.down = 1; s.toGo = Math.min(10, 100 - s.ballOn);
  };
  const other = t => t === 'a' ? 'b' : 'a';
  const scoreTD = (team, desc) => {
    s.score[team] += 6; entry.pts = 6; entry.ptsTeam = team; entry.ev = 'td';
    if (!st.ot) {
      const good = R() < clamp(0.90 + (U[team].k - 60) * 0.002, 0.7, 0.995);
      if (good) { s.score[team] += 1; entry.pts = 7; desc += ' The extra point is good.'; }
      else desc += ' The extra point is missed.';
    }
    giveBall(other(team), 25);
    return desc;
  };
  const safety = (desc) => {
    s.score[d] += 2; entry.pts = 2; entry.ptsTeam = d; entry.ev = 'safety';
    giveBall(d, 35);
    return desc + ' Safety, two points.';
  };
  // shared yardage application for completed runs / passes
  const advance = (y, desc) => {
    const nb = st.ballOn + y;
    entry.yards = y;
    if (nb >= 100) return scoreTD(o, desc + ' Touchdown!');
    if (nb <= 0) return safety(desc);
    if (y >= st.toGo) {
      s.ballOn = nb; s.down = 1; s.toGo = Math.min(10, 100 - nb); entry.firstDown = true;
      return desc + ' First down.';
    }
    s.ballOn = nb; s.toGo = st.toGo - y; s.down = st.down + 1;
    if (s.down > 4) { giveBall(d, 100 - nb); entry.ev = 'downs'; return desc + ' Turnover on downs.'; }
    return desc;
  };
  const yds = y => Math.abs(y) === 1 ? '1 yard' : Math.abs(y) + ' yards';

  if (offPick === 'PUNT') {
    const dist = Math.round(clamp(38 + (OU.k - 55) * 0.22 + gauss() * 5, 22, 62));
    const land = st.ballOn + dist;
    entry.ev = 'punt'; entry.anim = 'punt'; entry.travel = dist;
    if (land >= 100) {
      giveBall(d, 20);
      entry.text = nm(o, 'K') + ' punts it into the end zone. Touchback.';
    } else {
      const ret = Math.max(0, Math.round(R() * 6 * (0.6 + DU.s / 100)));
      giveBall(d, 100 - land + ret);
      entry.text = nm(o, 'K') + ' punts ' + dist + ' yards' + (ret > 2 ? ', returned ' + ret : '') + '.';
    }
  } else if (offPick === 'FG') {
    const dist = fgDist(st);
    const p = clamp(0.985 - Math.max(0, dist - 24) * 0.0175 + (OU.k - 60) * 0.004, 0.04, 0.99);
    entry.anim = 'fg'; entry.travel = 100 - st.ballOn;
    if (R() < p) {
      s.score[o] += 3; entry.pts = 3; entry.ptsTeam = o; entry.ev = 'fg';
      giveBall(d, 25);
      entry.text = nm(o, 'K') + ' drills a ' + dist + '-yard field goal. Three points.';
    } else {
      entry.ev = 'fgmiss';
      giveBall(d, Math.max(20, 100 - st.ballOn + 7));
      entry.text = nm(o, 'K') + ' misses from ' + dist + ' yards.';
    }
  } else if (OFF[offPick].kind === 'run') {
    const inside = offPick === 'RUN_IN';
    const m = MATCH[defPick][offPick], eff = 1 + 0.30 * m;
    const Orun = (inside ? 0.42 * OU.h + 0.38 * OU.ol + 0.20 * OU.fbq
                         : 0.50 * OU.h + 0.30 * OU.ol + 0.20 * OU.wr) + (inside && OU.hasFB ? 2 : 0);
    const Drun = 0.38 * DU.dl + 0.36 * DU.lb + 0.14 * DU.s + 0.12 * DU.cb + (DU.scheme === '43' ? 3 : 0);
    const diff = Orun - Drun * eff;
    let y = Math.round((inside ? 3.9 : 4.3) + diff * 0.10 + gauss() * (inside ? 2.8 : 3.8));
    const bigP = (inside ? 0.035 : 0.07) + Math.max(0, OU.hSpd - 55) / 700;
    if (R() < bigP * (1 - m * 0.25)) y += Math.round(8 + R() * 20);
    y = Math.max(y, -4);
    const useFB = inside && OU.hasFB && R() < 0.25;
    const runner = nm(o, useFB ? 'FB' : 'HB'); entry.runId = useFB ? 'FB' : 'HB';
    const fumP = 0.010 + Math.max(0, DU.dl - OU.ol) * 0.0003;
    const lost = R() < fumP && R() < 0.5;
    entry.anim = 'run';
    const spot = Math.max(0, st.ballOn + Math.max(0, y));
    if (lost) {
      entry.ev = 'fumble'; entry.yards = Math.max(0, y); entry.travel = Math.max(0, y);
      giveBall(d, 100 - Math.min(spot, 98));
      entry.text = runner + ' fumbles and ' + teams[d].name + ' recovers.';
    } else {
      entry.travel = y;
      let desc;
      if (y <= 0) desc = y === 0 ? runner + ' is stuffed for no gain.' : runner + ' is dropped for a loss of ' + yds(y) + '.';
      else if (y >= 15) desc = runner + ' breaks free for ' + yds(y) + '.';
      else desc = runner + ' runs for ' + yds(y) + '.';
      entry.text = advance(y, desc);
      if (entry.ev === 'play') entry.ev = 'run';
    }
  } else {
    // pass
    const spec = OFF[offPick];
    const m = MATCH[defPick][offPick], eff = 1 + 0.30 * m;
    const blitz = defPick === 'BLITZ';
    const rush = 0.6 * DU.dl + 0.4 * DU.lb + (blitz ? 7 : 0) + (defPick === 'PREVENT' ? -4 : 0) + (DU.scheme === '34' ? 2 : 0);
    const prot = OU.ol;
    const sackP = clamp(0.055 + (rush - prot) * 0.0035 + (blitz ? 0.05 : 0) + (defPick === 'PREVENT' ? -0.02 : 0)
                        - (offPick === 'SCREEN' ? 0.03 : 0) - (offPick === 'PASS_S' ? 0.025 : 0), 0.01, 0.30);
    const pressure = Math.max(0, rush - prot) * 0.0030 + (blitz ? 0.04 : 0);
    const cov = 0.45 * DU.cb + 0.30 * DU.s + 0.25 * DU.lb;
    // target
    let tgt;
    if (offPick === 'SCREEN' && R() < 0.7) tgt = { id: 'HB', fit: OU.h, spd: OU.hSpd };
    else {
      let tot = 0;
      const ws = OU.recv.map(r => {
        let w = Math.pow(r.fit / 100, 2);
        if (offPick === 'PASS_D') w *= r.spd / 60;
        if (offPick === 'PASS_S' && r.id === 'TE') w *= 1.2;
        tot += w; return w;
      });
      let x = R() * tot; tgt = OU.recv[OU.recv.length - 1];
      for (let i = 0; i < ws.length; i++) { x -= ws[i]; if (x <= 0) { tgt = OU.recv[i]; break; } }
    }
    const qb = nm(o, 'QB'), rec = nm(o, tgt.id); entry.qbId = 'QB'; entry.recId = tgt.id;
    const O = 0.38 * OU.q + 0.42 * tgt.fit + 0.20 * OU.ol + ((offPick === 'PASS_S' || offPick === 'SCREEN') && !OU.hasFB ? 2 : 0);
    const compP = clamp(spec.base + (O - cov * eff) * 0.0070 - pressure, 0.08, 0.93);
    const intP = clamp(0.028 + (cov * eff - OU.q) * 0.0012 + (offPick === 'PASS_D' ? 0.025 : 0) - (offPick === 'SCREEN' ? 0.02 : 0), 0.006, 0.12);
    const r1 = R();
    if (r1 < sackP) {
      const loss = Math.round(3 + R() * 5 + (blitz ? 1.5 : 0));
      const wid = DU.rushers[Math.floor(R() * DU.rushers.length)], who = nm(d, wid); entry.defId = wid;
      entry.anim = 'sack'; entry.travel = -loss; entry.yards = -loss; entry.ev = 'sack';
      const nb = st.ballOn - loss;
      if (nb <= 0) { entry.text = safety(who + ' sacks ' + qb + ' in the end zone.'); }
      else {
        s.ballOn = nb; s.toGo = st.toGo + loss; s.down = st.down + 1;
        entry.text = who + ' sacks ' + qb + ' for a loss of ' + yds(loss) + '.';
        if (s.down > 4) { giveBall(d, 100 - nb); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
      }
    } else if (R() < compP) {
      let y = Math.round(spec.avg * (0.55 + 0.9 * R()) + (O - cov * eff) * 0.10);
      const bigP = 0.05 + Math.max(0, tgt.spd - 60) / 500;
      if (R() < bigP) y += Math.round(6 + R() * 18);
      y = clamp(y, 0, 100 - st.ballOn);
      entry.anim = 'pass'; entry.travel = y;
      const desc = y >= 20 ? qb + ' connects deep with ' + rec + ' for ' + yds(y) + '.'
                 : y === 0 ? qb + ' finds ' + rec + ' but he is stopped for no gain.'
                 : qb + ' finds ' + rec + ' for ' + yds(y) + '.';
      entry.text = advance(y, desc);
      if (entry.ev === 'play') entry.ev = 'pass';
    } else if (R() < intP / Math.max(0.2, 1 - compP)) {
      const wid = DU.hawks[Math.floor(R() * DU.hawks.length)], who = nm(d, wid); entry.defId = wid;
      entry.anim = 'int'; entry.travel = spec.depth; entry.ev = 'int';
      const spot = st.ballOn + spec.depth;
      if (spot >= 100) { giveBall(d, 20); entry.text = qb + ' is picked off in the end zone by ' + who + '. Touchback.'; }
      else if (R() < 0.04) { entry.text = scoreTD(d, qb + ' is picked off by ' + who + ', who takes it all the way back!'); entry.ev = 'int'; }
      else {
        const ret = Math.round(R() * 14);
        giveBall(d, 100 - spot + ret);
        entry.text = qb + ' is picked off by ' + who + '.';
      }
    } else {
      entry.anim = 'inc'; entry.travel = Math.max(2, spec.depth - 2); entry.ev = 'inc';
      s.toGo = st.toGo; s.down = st.down + 1; s.ballOn = st.ballOn;
      entry.text = qb + "'s pass for " + rec + ' falls incomplete.';
      if (s.down > 4) { giveBall(d, 100 - st.ballOn); entry.ev = 'downs'; entry.text += ' Turnover on downs.'; }
    }
  }

  // clock + quarters
  s.playNo = st.playNo + 1;
  const changed = s.score.a !== st.score.a || s.score.b !== st.score.b;
  if (st.ot) {
    if (changed || s.playNo >= 4 * PQ + OT_MAX) s.over = true;
  } else if (s.playNo === 2 * PQ) {
    giveBall(other(st.firstRecv), 25); entry.half = true;
  } else if (s.playNo === 4 * PQ) {
    if (s.score.a === s.score.b) { s.ot = true; giveBall(st.firstRecv, 25); entry.otStart = true; }
    else s.over = true;
  }
  if (s.over) s.winner = s.score.a > s.score.b ? 'a' : s.score.b > s.score.a ? 'b' : null;
  entry.after = { poss: s.poss, ballOn: s.ballOn, down: s.down, toGo: s.toGo };
  entry.score = { a: s.score.a, b: s.score.b };
  return { state: s, entry };
}

function replay(seed, teams, moves, cpuSides) {
  cpuSides = cpuSides || [];
  let st = initState(seed);
  const log = [];
  const U = { a: teamUnits(teams.a), b: teamUnits(teams.b) };
  let guard = 0;
  while (!st.over && guard++ < 200) {
    const n = st.playNo, off = st.poss, def = off === 'a' ? 'b' : 'a';
    let om = moves[n + '-' + off];
    if (!om && cpuSides.indexOf(off) >= 0) om = { pick: cpuMove(st, U, off, seed, 'off') };
    if (!om) break;
    const kick = OFF[legalOff(st, om.pick)].kind === 'kick';
    let dm = moves[n + '-' + def];
    if (!dm && !kick && cpuSides.indexOf(def) >= 0) dm = { pick: cpuMove(st, U, def, seed, 'def') };
    if (!kick && !dm) break;
    const res = stepGame(st, teams, U, seed, om.pick, dm ? dm.pick : null);
    st = res.state; log.push(res.entry);
  }
  return { state: st, log, U };
}
// deterministic CPU decisions so a server can re-verify any game
function cpuMove(st, U, side, seed, role) {
  const rnd = mulberry32(hashStr(seed + ':cpu:' + st.playNo + ':' + side));
  return role === 'off' ? cpuOffense(st, U, side, rnd) : cpuDefense(st, rnd);
}

/* ================= CPU opponent ================= */
function cpuOffense(st, U, me, rnd) {
  rnd = rnd || Math.random;
  const OU = U[me];
  if (st.down === 4) {
    const dist = fgDist(st);
    if (dist <= 48 && rnd() < 0.9) return 'FG';
    if (st.toGo <= 2 && st.ballOn > 45 && rnd() < 0.6) return 'RUN_IN';
    if (st.ballOn < 62) return 'PUNT';
    if (dist <= 62 && rnd() < 0.5) return 'FG';
  }
  const passBias = clamp(0.5 + (OU.q + OU.wr - OU.h - OU.ol) * 0.004, 0.3, 0.7);
  if (st.toGo >= 8) return rnd() < passBias + 0.15 ? (rnd() < 0.5 ? 'PASS_M' : rnd() < 0.5 ? 'PASS_D' : 'PASS_S') : 'RUN_OUT';
  if (rnd() < passBias) { const x = rnd(); return x < 0.35 ? 'PASS_S' : x < 0.65 ? 'PASS_M' : x < 0.85 ? 'PASS_D' : 'SCREEN'; }
  return rnd() < 0.6 ? 'RUN_IN' : 'RUN_OUT';
}
function cpuDefense(st, rnd) {
  rnd = rnd || Math.random;
  const x = rnd();
  if (st.toGo <= 3) return x < 0.45 ? 'STACK' : x < 0.7 ? 'BLITZ' : x < 0.85 ? 'MAN' : 'ZONE';
  if (st.toGo >= 9) return x < 0.35 ? 'ZONE' : x < 0.55 ? 'PREVENT' : x < 0.8 ? 'MAN' : 'BLITZ';
  return x < 0.3 ? 'ZONE' : x < 0.5 ? 'MAN' : x < 0.7 ? 'STACK' : x < 0.9 ? 'BLITZ' : 'PREVENT';
}

