// the two-point chart, second half only: go for two when it turns the margin into one that matters (score is after the touchdown)
const GO2 = { 1: 1, 4: 1, 5: 1, 12: 1, 19: 1, '-2': 1, '-5': 1, '-9': 1, '-10': 1, '-13': 1 };
function cpuGo2(s, team) { return s.q >= 3 && !s.ot && !!GO2[s.score[team] - s.score[oth(team)]]; }
// the computer onside kicks when it is behind late in the fourth quarter
function cpuKick(st, me, rnd) {
  if (st.ot || st.q !== 4) return 'KO';
  const lead = st.score[me] - st.score[oth(me)];
  if (lead >= 0 || lead < -16) return 'KO';
  return st.clock <= 100 && rnd() < (st.clock <= 60 ? 0.95 : 0.6) ? 'ONSIDE' : 'KO';
}
// the computer calls a timeout when the clock matters and it is behind (or tied with the ball)
function cpuTO(st, me) {
  if (!(st.ro > 0) || !(st.to[me] > 0) || st.ot) return false;
  const lead = st.score[me] - st.score[oth(me)];
  if (st.q === 2) return st.clock <= 30 && (st.poss === me ? lead <= 7 : lead < 0);
  if (st.q === 4) return st.poss === me ? lead <= 0 && st.clock <= 45 : lead < 0 && st.clock <= 70;
  return false;
}
function cpuOffCat(st, U, me, rnd) {
  const OU = U[me];
  const lead = st.score[me] - st.score[oth(me)];
  if (st.q === 4 && !st.ot && lead > 0 && st.down <= 3 && st.clock <= (CAP + 3) * (4 - st.down)) return 'KNEEL';
  if (!st.ot && (st.q === 2 || (st.q === 4 && lead <= 0)) && st.ro > 0 && st.down <= 3 && st.clock <= 12 && fgDist(st) <= 50) return 'SPIKE';
  if (!st.ot && (st.q === 2 || (st.q === 4 && lead < 0)) && st.clock <= 40 && st.down < 4 && fgDist(st) > 20) return ['PASS_S', 'PASS_M', 'PASS_M', 'PASS_D'][Math.floor(rnd() * 4)];
  if (st.down === 4) {
    const dist = fgDist(st);
    if (dist <= 48 && rnd() < 0.9) return 'FG';
    if (st.toGo <= 2 && st.ballOn > 45 && rnd() < 0.6) return 'RUN_IN';
    if (st.ballOn < 62) return st.toGo <= 4 && st.ballOn > 35 && rnd() < 0.06 ? 'FAKEPUNT' : 'PUNT';
    if (dist <= 62 && rnd() < 0.5) return 'FG';
  }
  if (st.down >= 2 && st.down <= 3 && st.toGo >= 6 && rnd() < 0.03) return 'TRICK';   // now and then the CPU gets cute
  const passBias = clamp(0.5 + (OU.q + OU.wr - OU.h - OU.ol) * 0.004, 0.3, 0.7);
  if (st.toGo >= 8) return rnd() < passBias + 0.15 ? (rnd() < 0.5 ? 'PASS_M' : rnd() < 0.5 ? 'PASS_D' : 'PASS_S') : 'RUN_OUT';
  if (rnd() < passBias) { const x = rnd(); return x < 0.35 ? 'PASS_S' : x < 0.65 ? 'PASS_M' : x < 0.85 ? 'PASS_D' : 'SCREEN'; }
  return rnd() < 0.6 ? 'RUN_IN' : 'RUN_OUT';
}
function cpuDefCat(st, rnd) {
  const x = rnd();
  if (st.toGo <= 3) return x < 0.45 ? 'STACK' : x < 0.7 ? 'BLITZ' : x < 0.85 ? 'MAN' : 'ZONE';
  if (st.toGo >= 9) return x < 0.35 ? 'ZONE' : x < 0.55 ? 'PREVENT' : x < 0.8 ? 'MAN' : 'BLITZ';
  return x < 0.3 ? 'ZONE' : x < 0.5 ? 'MAN' : x < 0.7 ? 'STACK' : x < 0.9 ? 'BLITZ' : 'PREVENT';
}

// pick one of the plays in a category, weighted by the situation and by what the team is good at
function pickWeighted(ids, w, rnd) {
  let tot = 0; const ws = ids.map(id => { const v = Math.max(0, w[id] == null ? 1 : w[id]); tot += v; return v; });
  let x = rnd() * tot;
  for (let i = 0; i < ids.length; i++) { x -= ws[i]; if (x <= 0) return ids[i]; }
  return ids[ids.length - 1];
}
function cpuOffense(st, U, me, rnd) {
  rnd = rnd || Math.random;
  const c = cpuOffCat(st, U, me, rnd), OU = U[me];
  if (OFF[c].cat === 'SPEC') return c;
  const ids = Object.keys(OFF).filter(id => OFF[id].cat === c && legalOff(st, id) === id);
  const short = st.toGo <= 2, long = st.toGo >= 7, late = st.q === 4 && st.clock <= 60 && st.score[me] < st.score[oth(me)];
  const w = {
    DIVE: short ? 4 : 0.15, DRAW: long ? 1.3 : 0.5, POWER: 1, SWEEP: short ? 0.2 : 0.8, COUNTER: 0.9,
    HITCH: st.toGo <= 5 ? 1.5 : 0.8, MESH: 1.2, STICK: OU.recv[2].fit >= 78 ? 1.6 : 0.7,
    CURLS: st.toGo <= 10 ? 1.2 : 0.8, FLOOD: 1, YCROSS: OU.recv[2].fit >= 78 ? 1.4 : 0.8,
    POST: 1.2, GO: late ? 1.6 : 0.6, PA_DEEP: OU.h + OU.ol >= 150 ? 1.2 : 0.5,
    BUBBLE: 1, TUNNEL: 1
  };
  return pickWeighted(ids, w, rnd);
}
function cpuDefense(st, rnd) {
  rnd = rnd || Math.random;
  const c = cpuDefCat(st, rnd), ids = Object.keys(DEF_CALLS).filter(id => DEF_CALLS[id].cat === c);
  const goal = st.ballOn >= 93, longs = st.toGo >= 9, endgame = st.q === 4 && st.clock <= 45;
  const w = { STACK: goal ? 0.6 : 1, GOALLINE: goal ? 4 : 0, RUNBLITZ: 0.8, ZONE: 1, COV3: 1, COV4: longs ? 1.6 : 0.8, MAN: 1, MAN2: 0.7, TIGHT: goal ? 1.5 : 0.5,
              BLITZ: 0.6, ZBLITZ: 1, CBBLITZ: 0.7, PREVENT: endgame ? 3 : 0.6, SOFT: endgame ? 0.5 : 1 };
  return pickWeighted(ids, w, rnd);
}

/* ================= coach's pick (like Ask Madden) =================
   A suggestion for the side about to call a play: what the other team has called in this kind of spot this game (from the log, so it
   never sees this snap's call), blended with what teams usually do there, and the call that fares best against that, nudged by the
   situation and by what the team is good at. Returns { id, why }. */
const SIT_PRIOR = {
  off: { s: { RUN_IN: .40, RUN_OUT: .20, PASS_S: .20, PASS_M: .12, PASS_D: .05, SCREEN: .03 }, m: { RUN_IN: .25, RUN_OUT: .17, PASS_S: .20, PASS_M: .17, PASS_D: .12, SCREEN: .09 },
         l: { RUN_IN: .05, RUN_OUT: .20, PASS_S: .20, PASS_M: .25, PASS_D: .20, SCREEN: .10 } },
  def: { s: { STACK: .45, BLITZ: .25, MAN: .15, ZONE: .15, PREVENT: 0 }, m: { ZONE: .30, MAN: .20, STACK: .20, BLITZ: .20, PREVENT: .10 }, l: { ZONE: .35, PREVENT: .20, MAN: .25, BLITZ: .20, STACK: 0 } }
};
const sitOf = b => b.toGo <= 3 ? 's' : b.toGo >= 8 ? 'l' : 'm';
const sitLabel = st => (st.down === 1 ? '1st' : st.down === 2 ? '2nd' : st.down === 3 ? '3rd' : '4th') + ' and ' + (st.toGo === 10 && st.down === 1 ? '10' : st.toGo <= 3 ? 'short' : st.toGo >= 8 ? 'long' : 'medium');
// expected points for the team with the ball, roughly: field position, down and distance (the coach's pick compares snaps by it)
const EP_DOWN = [0, 0, 0.45, 1.0, 1.9], COACH = { risk: 0.6, chains: 0.4 };
const epOf = (s, me) => { if (s.over || s.kick) return 0; const v = 0.075 * s.ballOn - 1.6 - EP_DOWN[s.down] - 0.045 * s.toGo; return s.poss === me ? v : -v; };
function suggest(st, log, teams, U, me, role) {
  const opp = oth(me), lead = st.score[me] - st.score[opp];
  if (st.pat) {
    if (role === 'def') return { id: 'GOALLINE', picks: ['GOALLINE', 'TIGHT', 'MAN'], why: 'They need two yards or a kick: load up the goal line, or play tight man if you expect a pass.' };
    const go = cpuGo2(st, me);
    return go ? { id: 'DIVE', picks: ['DIVE', 'PASS_S', 'XP'], why: 'The chart says go for two here: a two-point lead or deficit changes the game.' } : { id: 'XP', picks: ['XP', 'DIVE', 'PASS_S'], why: 'Take the point. Go for two (call any run or pass) only when the score says so.' };
  }
  if (st.kick) { const k = cpuKick(st, me, () => 0.5); return { id: k, picks: [k], why: k === 'ONSIDE' ? 'You need the ball back: try the onside kick.' : 'Kick it deep and make them go the length of the field.' }; }
  if (role === 'off') {
    const c = cpuOffCat(st, U, me, () => 0.5);
    if (OFF[c] && OFF[c].cat === 'SPEC' && legalOff(st, c) === c) return { id: c, picks: [c], why: { KNEEL: 'Kneel: you have the lead and the clock does the rest.', SPIKE: 'Spike it to stop the clock.', FG: 'Take the points: a ' + fgDist(st) + '-yard field goal.', PUNT: 'Too far to go for it here: punt it away.' }[c] || '' };
  }
  // what they are likely to call: their calls this game (the same kind of down and distance counts most), blended with the usual
  const prior = SIT_PRIOR[role === 'off' ? 'def' : 'off'][sitOf(st)], cnt = {}; let seen = 0, same = 0;
  (log || []).forEach(e => {
    if (!e.offPick || !e.defPick || !e.before || e.before.kick) return;
    const theirs = role === 'off' ? (e.off === me ? DEF_CALLS[e.defPick] && DEF_CALLS[e.defPick].cat : null) : (e.off === opp && OFF[e.offPick] ? OFF[e.offPick].cat : null);
    if (!theirs || !(theirs in prior)) return;
    const w = sitOf(e.before) === sitOf(st) ? 1 + (e.before.down >= 3) * (st.down >= 3) * 0.5 : 0.3;
    cnt[theirs] = (cnt[theirs] || 0) + w; seen += w; if (sitOf(e.before) === sitOf(st)) same++;
  });
  const P = {}; Object.keys(prior).forEach(k => { P[k] = (prior[k] * 3 + (cnt[k] || 0)) / (3 + seen); });
  const top = Object.keys(P).sort((a, b) => P[b] - P[a])[0];
  // play each pairing out a few times with the stat engine (seeded, so the same spot gives the same advice) and score it in expected points
  // (a little risk-averse: a coach would rather move the chains than chase the long ball every snap)
  const K = 16, base = Object.assign({}, st), ep0 = epOf(st, me), sc0 = st.score[me] - st.score[opp];
  const value = (o, d) => { let v = 0, v2 = 0; for (let k = 0; k < K; k++) { const r = stepGame(Object.assign({}, base, { playNo: 9000 + k }), teams, U, 'coach:' + st.playNo, o, d).state, x = (r.score[me] - r.score[opp] - sc0) + epOf(r, me) - ep0 + (r.poss === base.poss && r.down === 1 && r.score[me] === base.score[me] && r.score[opp] === base.score[opp] ? COACH.chains : 0) * (base.poss === me ? 1 : -1); v += x; v2 += x * x; } v /= K; return v - COACH.risk * Math.sqrt(Math.max(0, v2 / K - v * v)); };
  const offIds = Object.keys(OFF).filter(id => OFF[id].cat !== 'SPEC' && legalOff(st, id) === id), coachIds = offIds.filter(id => OFF[id].cat !== 'TRICK');   // (tricks are your call, not the coach's)
  const scored = [];
  if (role === 'off') {
    const defs = Object.keys(DEF_CALLS).filter(d => P[DEF_CALLS[d].cat] > 0), per = c => defs.filter(d => DEF_CALLS[d].cat === c).length;
    coachIds.forEach(id => scored.push({ id, sc: defs.reduce((t, d) => t + P[DEF_CALLS[d].cat] / per(DEF_CALLS[d].cat) * value(id, d), 0) }));
  } else {
    const plays = offIds.filter(id => P[OFF[id].cat] > 0), per = c => plays.filter(id => OFF[id].cat === c).length;
    const goal = st.ballOn >= 93, endgame = st.q >= 4 && st.clock <= 45 && lead > 0;
    Object.keys(DEF_CALLS).forEach(d => {
      if (d === 'GOALLINE' && !goal) return;
      let sc = plays.reduce((t, id) => t + P[OFF[id].cat] / per(OFF[id].cat) * value(id, d), 0);
      if (endgame && DEF_CALLS[d].cat === 'PREVENT') sc += 0.3;   // nothing deep
      scored.push({ id: d, sc });
    });
  }
  // the best call, and the best of two other sections as alternatives (so the advice is not the same play every snap)
  const catOf = id => role === 'off' ? OFF[id].cat : DEF_CALLS[id].cat;
  scored.sort((a, b) => b.sc - a.sc || (a.id < b.id ? -1 : 1));
  const picks = [], add = f => { const x = scored.find(x => picks.indexOf(x.id) < 0 && !picks.some(p => catOf(p) === catOf(x.id)) && f(x.id)); if (x) picks.push(x.id); };
  add(() => true);
  if (role === 'off') { const run = id => OFF[id].kind === 'run'; add(id => run(id) !== run(picks[0])); }   // a run and a pass, like Ask Madden
  add(() => true);
  if (role === 'def') add(() => true);
  const best = picks[0];
  const catName = id => ((role === 'off' ? DEF_CATS : OFF_CATS).find(c => c.id === id) || {}).label || id;
  const seenTxt = same >= 2 ? 'they have shown it about ' + Math.round(P[top] * 100) + '% of the time' : 'what teams usually do';
  const why = role === 'off'
    ? 'Expect ' + catName(top) + ' on ' + sitLabel(st) + ' (' + seenTxt + '). ' + OFF[best].label + ' gains the most against what they are likely to call.'
    : 'Expect ' + catName(top).toLowerCase() + ' on ' + sitLabel(st) + ' (' + seenTxt + '). ' + DEF_CALLS[best].label + ' gives up the least against it.';
  return { id: best, why, picks };
}

